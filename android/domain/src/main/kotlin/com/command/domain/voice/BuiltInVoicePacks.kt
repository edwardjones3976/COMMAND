    /** The personality a pack's words go with; null for a pack that is not one of the ten. */
    fun personalityOf(packId: String): Personality? = directors[packId]?.personality

    /** Whether the pack's voice should be a woman's; null when it does not say, as a person's own pack does not. */
    fun isFemale(packId: String): Boolean? = directors[packId]?.female

    /** The Studio voice the voice engine gives the pack; null for a pack that is not one of the ten. */
    fun geminiVoiceOf(packId: String): String? = directors[packId]?.geminiVoice

    /** The pack's loudness trim in dB: +1 dB per 10 % of boost, from nothing at 100 % up to the most a trim can be. */
    fun trimDb(pack: VoicePackEntity): Float = ((pack.volumeBoostPercent - 100) / 10f).coerceIn(0f, MAX_TRIM_DB)

